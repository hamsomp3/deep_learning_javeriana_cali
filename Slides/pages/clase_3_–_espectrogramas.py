def plot_3d_spectrogram(spectrogram):
    """
    Plots a 3D spectrogram using Plotly.

    Args:
    spectrogram (tensorflow.Tensor): A 2D tensor containing spectrogram data.

    Returns:
    None: Displays a 3D plot.
    """
    # Convert the spectrogram to a numpy array for plotting
    spectrogram_np = spectrogram.numpy()

    # Get the magnitude of the spectrogram
    magnitude = np.abs(spectrogram_np)

    # Create x, y, z data for 3D plotting
    x = np.arange(magnitude.shape[1])
    y = np.arange(magnitude.shape[0])
    X, Y = np.meshgrid(x, y)
    Z = magnitude

    # Create a 3D surface plot
    fig = go.Figure(data=[go.Surface(z=Z, x=X, y=Y, colorscale='Viridis')])
    fig.update_layout(title='3D Spectrogram', autosize=True,
                    margin=dict(l=65, r=50, b=65, t=90))
    fig.write_html(imagen_path.joinpath('Clase 2 - 3D Spectrogram.html'), auto_open=False)
    fig.show()

