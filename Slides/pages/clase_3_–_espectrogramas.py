def plot_training_loss(loss_data, imagen_path, title='Training Loss Evolution', yaxis='Loss', xaxis='Epochs', label_line='Last Training Loss'):
    """
    Plots the training loss evolution over epochs and adds a dotted horizontal line at the last loss value.

    Parameters:
        loss_data (list): A list containing the loss values for each training epoch.
        imagen_path (Path): Directory path where the graphs will be saved.
        title (str, optional): The title of the plot. Defaults to 'Training Loss Evolution'.

    Returns:
        None: Displays the plot.
    """
    epochs = range(1, len(loss_data) + 1)

    # Creating a DataFrame for use with Plotly Express
    data = pd.DataFrame({
        'Epochs': list(epochs),
        yaxis: loss_data
    })

    # Creating the line plot
    fig = px.line(data, x='Epochs', y=yaxis, title=title)

    # Adding a horizontal dotted line at the last training loss value
    last_loss = loss_data[-1]  # Last training loss value
    fig.add_hline(y=last_loss, line_dash="dot",
                annotation_text=f"{label_line}: {last_loss:.4f}",
                annotation_position="top right")

    # Updating the layout to add more details
    fig.update_layout(
        xaxis_title=xaxis,
        yaxis_title=yaxis,
        legend_title="Legend",
        title={'text': title, 'y':0.9, 'x':0.5, 'xanchor': 'center', 'yanchor': 'top'}
    )

    # Saving the plot as an HTML file
    fig.write_html(imagen_path.joinpath(f'{title}.html'), auto_open=False)
    fig.show()

