def plot_spectrogram(spectrogram, title='Spectrogram'):
    """
    Plot a spectrogram using Plotly.

    Args:
    spectrogram (numpy.ndarray): Array containing the spectrogram data.
    title (str): Title of the plot.

    Returns:
    plotly.graph_objects.Figure: A Plotly figure object.
    """
    # Avoid taking the logarithm of zero by adding a small number
    epsilon = 1e-10
    # log_spec = np.log(spectrogram.T + epsilon)
    log_spec = np.log(spectrogram.T)
    height = log_spec.shape[0]
    width = log_spec.shape[1]

    # Creating the x and y scales
    x = np.linspace(0, spectrogram.shape[1], num=width)
    y = np.linspace(0, spectrogram.shape[0], num=height)

    # Create a plotly figure
    fig = go.Figure(data=go.Heatmap(
        z=log_spec,
        x=x,
        y=y,
        colorscale='Viridis'
    ))

    fig.update_layout(
        title=title,
        xaxis_title='Time',
        yaxis_title='Frequency',
        xaxis=dict(showgrid=False),
        yaxis=dict(showgrid=False),
    )

    return fig

