# Se define una función que con las muestras del archivo de audio, genera el
# espectograma
def preprocess(wave):
    """
    Generates a spectrogram from the first 16000 samples of the audio wave.

    Args:
    wave (numpy.ndarray): Audio wave array.

    Returns:
    tensorflow.Tensor: Spectrogram represented as a 2D tensor.
    """
    wav = wave[:16000]
    spectrogram = tf.signal.stft(wav, frame_length=255, frame_step=128)
    spectrogram = tf.abs(spectrogram)
    return spectrogram

